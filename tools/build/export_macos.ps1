<#
.SYNOPSIS
  One-command macOS release for Hype Raiders, built FROM WINDOWS.

  Produces export/v<version>/mac/HypeRaiders-v<version>-mac.zip — a zip (made by Godot
  itself) containing the universal (Apple Silicon arm64 + Intel x86_64) "Hype Raiders.app"
  with the game .pck embedded and an AD-HOC code signature (required on Apple Silicon;
  Godot signs it cross-platform, no Xcode needed). A README-mac.txt with the Gatekeeper
  first-launch instructions is written NEXT to the zip.

  IMPORTANT: the Godot-made zip is shipped AS-IS. Never unpack + re-zip the .app on
  Windows — Windows zip tools strip the unix executable bits and the app stops launching.

  The build is UNSIGNED in the Apple sense (no Developer ID / notarization): on first
  launch macOS shows a Gatekeeper warning — right-click -> Open -> Open (or
  `xattr -cr "Hype Raiders.app"`). That's expected for a friends build.

.EXAMPLE
  pwsh tools/build/export_macos.ps1
  pwsh tools/build/export_macos.ps1 -Version 0.3.0
#>
param(
    # The Godot 4.6.3 console executable (used headless to export).
    [string]$Godot = "C:\Users\illya\Desktop\godot\Godot_v4.6.3-stable_win64_console.exe",
    # Release version; defaults to the contents of the VERSION file at the repo root.
    [string]$Version = "",
    # Build-timestamp subfolder (yyyy-MM-dd_HH-mm-ss). When called from export_all.ps1 the
    # SAME stamp is passed to both platforms so they land together. Empty = generate now.
    [string]$Stamp = ""
)

$ErrorActionPreference = "Stop"
$GodotVersion = "4.6.3.stable"
$PresetName   = "macOS"

# Regenerate scripts/resource_index.gd from the data-driven .tres dirs (same as the
# Windows script): catalogs fall back to this list in EXPORTED builds because DirAccess
# can't enumerate a res:// directory inside a PCK.
function Write-ResourceIndex {
    param([string]$Proj)
    $cats = [ordered]@{ ITEMS = "resources/items"; ATTACHMENTS = "resources/attachments"; RECIPES = "resources/recipes"; QUESTS = "resources/quests" }
    $lines = @(
        "extends RefCounted",
        "class_name ResourceIndex",
        "## GENERATED by tools/build/export_*.ps1 — explicit .tres paths so the catalogs",
        "## work in EXPORTED builds (DirAccess can't enumerate a res:// dir inside a PCK).",
        "## Do not hand-edit.",
        ""
    )
    foreach ($k in $cats.Keys) {
        $dir = Join-Path $Proj $cats[$k]
        $lines += "const ${k}: PackedStringArray = ["
        if (Test-Path $dir) {
            foreach ($f in (Get-ChildItem -Path $dir -Filter *.tres -File | Sort-Object Name)) {
                $lines += "`t`"res://$($cats[$k])/$($f.Name)`","
            }
        }
        $lines += "]"
        $lines += ""
    }
    Set-Content -Path (Join-Path $Proj "scripts\resource_index.gd") -Value $lines -Encoding UTF8
    Write-Host "   regenerated scripts/resource_index.gd"
}

# --- Resolve paths (script lives in tools/build/, project is two levels up) ---
$ProjectDir = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
if ([string]::IsNullOrWhiteSpace($Version)) {
    $verFile = Join-Path $ProjectDir "VERSION"
    if (Test-Path $verFile) { $Version = (Get-Content $verFile -Raw).Trim() } else { $Version = "0.0.0" }
}
# Timestamped, per-platform output folder: export/v<Version>/<stamp>/mac/ — every build goes
# to a NEW dated folder so previous builds are PRESERVED for rollback. The stamp is shared
# with the Windows build when both are run via export_all.ps1.
if ([string]::IsNullOrWhiteSpace($Stamp)) { $Stamp = Get-Date -Format "yyyy-MM-dd_HH-mm-ss" }
$ExportDir  = Join-Path $ProjectDir "export\v$Version\$Stamp\mac"

Write-Host "== Hype Raiders — macOS release build (from Windows) ==" -ForegroundColor Cyan
Write-Host "  Project : $ProjectDir"
Write-Host "  Godot   : $Godot"
Write-Host "  Version : $Version"

if (-not (Test-Path $Godot)) {
    throw "Godot executable not found at '$Godot'. Pass -Godot <path to Godot_v4.6.3-stable_win64_console.exe>."
}

# --- 1) Ensure export templates are installed (one-time; same .tpz as Windows) -----
$TemplatesDir = Join-Path $env:APPDATA "Godot\export_templates\$GodotVersion"
$TemplateProbe = Join-Path $TemplatesDir "macos.zip"
if (-not (Test-Path $TemplateProbe)) {
    Write-Host "`n-- Export templates for $GodotVersion not found; installing (one-time ~700 MB) --" -ForegroundColor Yellow
    $tpzUrl = "https://github.com/godotengine/godot-builds/releases/download/4.6.3-stable/Godot_v4.6.3-stable_export_templates.tpz"
    $tmp    = Join-Path $env:TEMP "godot_templates_$GodotVersion"
    if (Test-Path $tmp) { Remove-Item $tmp -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $tmp | Out-Null
    $tpz = Join-Path $tmp "templates.tpz"
    Write-Host "   downloading $tpzUrl ..."
    $oldPref = $ProgressPreference; $ProgressPreference = "SilentlyContinue"
    try { Invoke-WebRequest -Uri $tpzUrl -OutFile $tpz } finally { $ProgressPreference = $oldPref }
    Write-Host "   extracting ..."
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [System.IO.Compression.ZipFile]::ExtractToDirectory($tpz, $tmp)
    $src = Join-Path $tmp "templates"
    if (-not (Test-Path $src)) { throw "Unexpected .tpz layout (no 'templates' folder). Install templates via the Godot editor instead." }
    New-Item -ItemType Directory -Force -Path $TemplatesDir | Out-Null
    Copy-Item (Join-Path $src "*") $TemplatesDir -Recurse -Force
    Remove-Item $tmp -Recurse -Force
    if (-not (Test-Path $TemplateProbe)) { throw "Template install failed (still no $TemplateProbe)." }
    Write-Host "   templates installed at $TemplatesDir" -ForegroundColor Green
} else {
    Write-Host "`n-- Export templates present ($GodotVersion, macos.zip) --" -ForegroundColor Green
}

# --- 2) Export the .zip containing the universal .app ------------------------------
Write-Host "`n-- Regenerating resource index --" -ForegroundColor Yellow
Write-ResourceIndex -Proj $ProjectDir

if (Test-Path $ExportDir) { Remove-Item $ExportDir -Recurse -Force }
New-Item -ItemType Directory -Force -Path $ExportDir | Out-Null
$ZipOut = Join-Path $ExportDir "HypeRaiders-v$Version-mac.zip"

Write-Host "`n-- Exporting (headless) --" -ForegroundColor Yellow
& $Godot --headless --path $ProjectDir --export-release $PresetName $ZipOut
# Godot can return non-zero on benign shutdown noise; trust the artifact instead.
if (-not (Test-Path $ZipOut) -or (Get-Item $ZipOut).Length -lt 10MB) {
    throw "Export did not produce a valid '$ZipOut' (check the preset name '$PresetName' and template install)."
}
$zipMB = [math]::Round((Get-Item $ZipOut).Length / 1MB, 1)
Write-Host "   exported HypeRaiders-v$Version-mac.zip ($zipMB MB)" -ForegroundColor Green

# --- 3) Validate WITHOUT re-zipping (re-zipping strips unix exec bits!) ------------
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [System.IO.Compression.ZipFile]::OpenRead($ZipOut)
try {
    $binEntry = $zip.Entries | Where-Object { $_.FullName -match "\.app/Contents/MacOS/" -and $_.Length -gt 1MB } | Select-Object -First 1
    if ($null -eq $binEntry) { throw "Zip has no .app/Contents/MacOS/ binary — not a valid app bundle." }
    Write-Host "   app binary : $($binEntry.FullName) ($([math]::Round($binEntry.Length/1MB,1)) MB)"
    # Mach-O FAT (universal) magic = CA FE BA BE — proves the x86_64+arm64 universal build.
    $s = $binEntry.Open()
    try {
        $magic = New-Object byte[] 4
        $read = $s.Read($magic, 0, 4)
        if ($read -eq 4 -and $magic[0] -eq 0xCA -and $magic[1] -eq 0xFE -and $magic[2] -eq 0xBA -and $magic[3] -eq 0xBE) {
            Write-Host "   binary is a UNIVERSAL (fat) Mach-O — runs natively on Apple Silicon + Intel" -ForegroundColor Green
        } else {
            Write-Host "   WARNING: binary is not a fat Mach-O (magic: $(($magic | ForEach-Object { $_.ToString('X2') }) -join ' ')) — check binary_format/architecture" -ForegroundColor Yellow
        }
    } finally { $s.Dispose() }
} finally { $zip.Dispose() }

# --- 4) README next to the zip (NOT inside — never repack the .app zip) ------------
$readme = @"
HYPE RAIDERS  v$Version  —  co-op extraction shooter  (macOS build)
====================================================================

REQUIREMENTS
  macOS 11+ on Apple Silicon (M1/M2/M3/M4) or macOS 10.12+ on Intel.
  The app is a universal binary — it runs natively on both.

FIRST LAUNCH (IMPORTANT — read this!)
  This build is not notarized with Apple (no `$99/yr developer cert), so
  macOS Gatekeeper will warn you the first time. That's expected. To run:
    1. Unzip HypeRaiders-v$Version-mac.zip (double-click it).
    2. RIGHT-CLICK (or Ctrl-click) "Hype Raiders.app" -> Open -> Open.
       (A plain double-click shows "can't be opened" — use right-click -> Open.)
  If macOS says the app "is damaged", clear the quarantine flag instead:
    open Terminal, cd to the folder, and run:
      xattr -cr "Hype Raiders.app"
    then open the app normally.

HOW TO PLAY
  From the menu:
    - SINGLE PLAYER : play solo.
    - HOST CO-OP    : you host. Configure your loadout, then DEPLOY.
    - JOIN CO-OP    : type the HOST's IP address, then JOIN, then DEPLOY.
    - SERVERS       : server browser (direct connect / favorites / LAN scan).
  Everyone must DEPLOY from the lobby for the match to begin.
  Up to 8 players. Cross-platform co-op works: a Mac can join a Windows
  host (and vice versa) — same game version required.

PLAYING WITH FRIENDS
  The game uses UDP PORT 24565 (LAN discovery: UDP 24566, local only).
    - SAME NETWORK: the host's local IP works, or just use SCAN LAN.
    - OVER THE INTERNET: the host forwards UDP 24565 and shares their
      public IP, OR everyone uses a free LAN-over-internet VPN
      (ZeroTier / Radmin VPN / Hamachi) — the easiest option.
  On Mac, find your local IP in System Settings -> Network (or `ipconfig
  getifaddr en0` in Terminal).

CONTROLS
  WASD move - Shift sprint - Space jump - LMB fire - RMB aim - R reload
  E interact/loot - I inventory - M map - 1-5 / wheel weapon - G grenade - H heal
  TAB scoreboard - T trade with a nearby teammate

NOTES
  - Saves live in: ~/Library/Application Support/Godot/app_userdata/Hype Raiders/
    Your progression is saved locally and survives game updates.
  - If performance is low, lower the graphics preset in Settings -> Graphics.

Have fun — and extract before the storm.
"@
Set-Content -Path (Join-Path $ExportDir "README-mac.txt") -Value $readme -Encoding UTF8

Write-Host "`n== DONE ==" -ForegroundColor Cyan
Write-Host "  Release zip : $ZipOut  ($zipMB MB)" -ForegroundColor Green
Write-Host "  README      : $(Join-Path $ExportDir 'README-mac.txt')"
Write-Host "  Share BOTH files. Friends unzip, then RIGHT-CLICK -> Open the app (first launch only)."
Write-Host "  NOTE: do not unzip + re-zip the app on Windows (it breaks the unix exec bits)."
