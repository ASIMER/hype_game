<#
.SYNOPSIS
  One-command portable Windows release for Hype Raiders.

  Produces a single self-contained HypeRaiders.exe (the game data .pck is embedded),
  bundles a README, and zips it as export/HypeRaiders-v<version>-win64.zip — ready to
  hand to friends: they unzip and double-click the exe.

  On first run it installs the matching Godot export templates if they're missing
  (one-time ~700 MB download), then skips that on later runs. Re-run anytime to cut a
  new release (bump the VERSION file first).

.EXAMPLE
  pwsh tools/build/export_windows.ps1
  pwsh tools/build/export_windows.ps1 -Version 0.2.0
#>
param(
    # The Godot 4.6.3 console executable (used headless to export).
    [string]$Godot = "C:\Users\illya\Desktop\godot\Godot_v4.6.3-stable_win64_console.exe",
    # Release version; defaults to the contents of the VERSION file at the repo root.
    [string]$Version = ""
)

$ErrorActionPreference = "Stop"
$GodotVersion = "4.6.3.stable"
$PresetName   = "Windows Desktop"

# Regenerate scripts/resource_index.gd from the data-driven .tres dirs. The catalogs
# (ItemCatalog/Crafting/Quests) fall back to this list in EXPORTED builds because
# DirAccess can't enumerate a res:// directory inside a PCK. Keeps releases current.
function Write-ResourceIndex {
    param([string]$Proj)
    $cats = [ordered]@{ ITEMS = "resources/items"; ATTACHMENTS = "resources/attachments"; RECIPES = "resources/recipes"; QUESTS = "resources/quests" }
    $lines = @(
        "extends RefCounted",
        "class_name ResourceIndex",
        "## GENERATED by tools/build/export_windows.ps1 — explicit .tres paths so the catalogs",
        "## work in EXPORTED builds (DirAccess can't enumerate a res:// dir inside a PCK).",
        "## Do not hand-edit.",
        ""
    )
    foreach ($k in $cats.Keys) {
        $dir = Join-Path $Proj $cats[$k]
        $lines += "const ${k}: PackedStringArray = ["
        if (Test-Path $dir) {
            foreach ($f in (Get-ChildItem -Path $dir -Filter *.tres -File | Sort-Object Name)) {
                $lines += "`t`"res://$($cats[$k])/$($f.Name)`","
            }
        }
        $lines += "]"
        $lines += ""
    }
    Set-Content -Path (Join-Path $Proj "scripts\resource_index.gd") -Value $lines -Encoding UTF8
    Write-Host "   regenerated scripts/resource_index.gd"
}

# --- Resolve paths (script lives in tools/build/, project is two levels up) ---
$ProjectDir = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$ExportDir  = Join-Path $ProjectDir "export"
if ([string]::IsNullOrWhiteSpace($Version)) {
    $verFile = Join-Path $ProjectDir "VERSION"
    if (Test-Path $verFile) { $Version = (Get-Content $verFile -Raw).Trim() } else { $Version = "0.0.0" }
}

Write-Host "== Hype Raiders — Windows release build ==" -ForegroundColor Cyan
Write-Host "  Project : $ProjectDir"
Write-Host "  Godot   : $Godot"
Write-Host "  Version : $Version"

if (-not (Test-Path $Godot)) {
    throw "Godot executable not found at '$Godot'. Pass -Godot <path to Godot_v4.6.3-stable_win64_console.exe>."
}

# --- 1) Ensure export templates are installed (one-time) -----------------------
$TemplatesDir = Join-Path $env:APPDATA "Godot\export_templates\$GodotVersion"
$TemplateProbe = Join-Path $TemplatesDir "windows_release_x86_64.exe"
if (-not (Test-Path $TemplateProbe)) {
    Write-Host "`n-- Export templates for $GodotVersion not found; installing (one-time ~700 MB) --" -ForegroundColor Yellow
    $tpzUrl = "https://github.com/godotengine/godot-builds/releases/download/4.6.3-stable/Godot_v4.6.3-stable_export_templates.tpz"
    $tmp    = Join-Path $env:TEMP "godot_templates_$GodotVersion"
    if (Test-Path $tmp) { Remove-Item $tmp -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $tmp | Out-Null
    $tpz = Join-Path $tmp "templates.tpz"
    Write-Host "   downloading $tpzUrl ..."
    $oldPref = $ProgressPreference; $ProgressPreference = "SilentlyContinue"
    try { Invoke-WebRequest -Uri $tpzUrl -OutFile $tpz } finally { $ProgressPreference = $oldPref }
    Write-Host "   extracting ..."
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [System.IO.Compression.ZipFile]::ExtractToDirectory($tpz, $tmp)
    # The .tpz holds a `templates/` folder; its contents go into <APPDATA>/.../4.6.3.stable/
    $src = Join-Path $tmp "templates"
    if (-not (Test-Path $src)) { throw "Unexpected .tpz layout (no 'templates' folder). Install templates via the Godot editor instead: Editor -> Manage Export Templates -> Download and Install." }
    New-Item -ItemType Directory -Force -Path $TemplatesDir | Out-Null
    Copy-Item (Join-Path $src "*") $TemplatesDir -Recurse -Force
    Remove-Item $tmp -Recurse -Force
    if (-not (Test-Path $TemplateProbe)) { throw "Template install failed (still no $TemplateProbe)." }
    Write-Host "   templates installed at $TemplatesDir" -ForegroundColor Green
} else {
    Write-Host "`n-- Export templates present ($GodotVersion) --" -ForegroundColor Green
}

# --- 2) Export the single embedded .exe ----------------------------------------
Write-Host "`n-- Regenerating resource index --" -ForegroundColor Yellow
Write-ResourceIndex -Proj $ProjectDir

if (Test-Path $ExportDir) { Remove-Item $ExportDir -Recurse -Force }
New-Item -ItemType Directory -Force -Path $ExportDir | Out-Null
$ExeOut = Join-Path $ExportDir "HypeRaiders.exe"

Write-Host "`n-- Exporting (headless) --" -ForegroundColor Yellow
& $Godot --headless --path $ProjectDir --export-release $PresetName $ExeOut
# Godot can return non-zero on benign shutdown noise; trust the artifact instead.
if (-not (Test-Path $ExeOut) -or (Get-Item $ExeOut).Length -lt 10MB) {
    throw "Export did not produce a valid '$ExeOut' (check the preset name '$PresetName' and template install)."
}
$exeMB = [math]::Round((Get-Item $ExeOut).Length / 1MB, 1)
Write-Host "   exported HypeRaiders.exe ($exeMB MB, pck embedded)" -ForegroundColor Green

# --- 3) Stage (exe + README) and zip -------------------------------------------
$StageName = "HypeRaiders-v$Version-win64"
$StageDir  = Join-Path $ExportDir $StageName
New-Item -ItemType Directory -Force -Path $StageDir | Out-Null
Copy-Item $ExeOut (Join-Path $StageDir "HypeRaiders.exe") -Force

$readme = @"
HYPE RAIDERS  v$Version  —  co-op extraction shooter
=====================================================

HOW TO PLAY
  Double-click HypeRaiders.exe. From the menu:
    - SINGLE PLAYER : play solo.
    - HOST CO-OP    : you host. Configure your loadout, then DEPLOY.
    - JOIN CO-OP    : type the HOST's IP address, then JOIN, then DEPLOY.
  Everyone must DEPLOY from the lobby for the match to begin.

PLAYING WITH FRIENDS
  The host shares their IP; friends type it into the JOIN field.
    - HOST: find your IP by opening Command Prompt and running:  ipconfig
            (use the "IPv4 Address" of your active adapter).
    - The game uses UDP PORT 24565 — allow HypeRaiders.exe through the
      Windows Firewall (a prompt usually appears on first host).

  SAME NETWORK (LAN / same Wi-Fi): the host's local IPv4 works directly.
  OVER THE INTERNET: either
    (a) the host forwards UDP port 24565 to their PC in their router, and
        friends use the host's PUBLIC IP (whatismyip.com); OR
    (b) everyone installs a free LAN-over-internet VPN (Radmin VPN /
        ZeroTier / Hamachi) and uses the VPN IP — no router setup needed.
        This is the easiest option.

CONTROLS
  WASD move · Shift sprint · Space jump · LMB fire · RMB aim · R reload
  E interact/loot · I inventory · M map · 1-5 / wheel weapon · G grenade · H heal

NOTES
  - Requires a Vulkan-capable GPU (virtually all Windows 10/11 PCs).
  - First launch may show a Windows SmartScreen warning because the build
    is unsigned — click "More info" -> "Run anyway".
  - Saves live in:  %APPDATA%\Godot\app_userdata\Hype Raiders\

Have fun — and extract before the storm.
"@
Set-Content -Path (Join-Path $StageDir "README.txt") -Value $readme -Encoding UTF8

$Zip = Join-Path $ExportDir "$StageName.zip"
if (Test-Path $Zip) { Remove-Item $Zip -Force }
Compress-Archive -Path (Join-Path $StageDir "*") -DestinationPath $Zip -Force

$zipMB = [math]::Round((Get-Item $Zip).Length / 1MB, 1)
Write-Host "`n== DONE ==" -ForegroundColor Cyan
Write-Host "  Release zip : $Zip  ($zipMB MB)" -ForegroundColor Green
Write-Host "  Share that zip — friends unzip and run HypeRaiders.exe."
